"""Generate the mechanical enum, configuration and statistics mappings.

The pinned public header is the input; no upstream checkout is needed.
Run this explicitly after reviewing an upstream API update.
"""
from pathlib import Path
import re
from api_docs import document, comment, variant_doc

ROOT = Path(__file__).resolve().parents[1]
JAVA = ROOT / 'api/src/main/java/io/bosonnetwork/quiche'
HEADER = (ROOT / 'native/quiche.h').read_text()
LICENSE = (ROOT / 'native/copyright-header.txt').read_text()
PRE = LICENSE + '// Generated by scripts/generate_api.py.\n\npackage io.bosonnetwork.quiche;\n\n'


def camel(s):
    return re.sub(r'_([a-z])', lambda m: m[1].upper(), s)


def write(name, body):
    (JAVA / (name + '.java')).write_text(document(name, PRE + body), encoding='ascii')


enums = [('quiche_error', 'QuicheError', 'QUICHE_ERR_'),
         ('quiche_cc_algorithm', 'CongestionControlAlgorithm', 'QUICHE_CC_'),
         ('quiche_shutdown', 'Shutdown', 'QUICHE_SHUTDOWN_'),
         ('quiche_path_event_type', 'PathEventType', 'QUICHE_PATH_EVENT_'),
         ('quiche_h3_error', 'H3Error', 'QUICHE_H3_'),
         ('quiche_h3_event_type', 'H3EventType', 'QUICHE_H3_EVENT_')]
values = {}
native_constants = []
for c_name, name, prefix in enums:
    body = re.search(r'enum ' + c_name + r'\s*\{(.*?)\};', HEADER, re.S)[1]
    comment_map = {match['name']: '\n'.join(re.findall(r'//+ ?([^\n]*)', match['docs']))
                   for match in re.finditer(r'(?P<docs>(?:[ \t]*//[^\n]*\n)+)\s*(?P<name>QUICHE_[A-Z0-9_]+)\s*(?:=|,)', body)}
    body = re.sub(r'//[^\n]*', '', body)
    items = []
    value = -1
    for item in body.split(','):
        item = item.strip()
        if not item:
            continue
        if '=' in item:
            key, expr = map(str.strip, item.split('='))
            for old, number in sorted(values.items(), key=lambda p: -len(p[0])):
                expr = expr.replace(old, str(number))
            value = int(eval(expr, {'__builtins__': {}}))
        else:
            key = item
            value += 1
        values[key] = value
        java_key = key.removeprefix(prefix)
        if name == 'H3Error':
            java_key = java_key.removeprefix('ERR_')
        description = variant_doc(name, java_key) or comment_map.get(key, '')
        items.append(comment(description or ('The ' + java_key + ' value.'), '    ') + f'    {java_key}({value})')
        native_constants.append(key)
    write(name, '/** Values from {@code ' + c_name + '}. */\npublic enum ' + name + ' {\n' +
          ',\n\n'.join(items) + ';\n\n    private final int code;\n\n'
          f'    {name}(int code) {{\n        this.code = code;\n    }}\n\n'
          '    public int code() {\n        return code;\n    }\n\n'
          f'    public static {name} fromCode(int code) {{\n'
          f'        for ({name} value : values()) {{\n'
          '            if (value.code == code)\n                return value;\n        }\n\n'
          '        throw new IllegalArgumentException("Unknown ' + name + ': " + code);\n    }\n}\n')

for name, items in [('PacketType', [('INITIAL', 1), ('RETRY', 2), ('HANDSHAKE', 3),
                                 ('ZERO_RTT', 4), ('SHORT', 5), ('VERSION_NEGOTIATION', 6)]),
                    ('PathState', [('FAILED', -1), ('UNKNOWN', 0), ('VALIDATING', 1),
                                   ('VALIDATING_MTU', 2), ('VALIDATED', 3)])]:
    write(name, 'public enum ' + name + ' {\n' +
          ',\n\n'.join(comment(variant_doc(name, key) or ('The ' + key + ' value.'), '    ') + f'    {key}({value})' for key, value in items) + ';\n\n'
          '    private final int code;\n\n'
          f'    {name}(int code) {{\n        this.code = code;\n    }}\n\n'
          '    public int code() {\n        return code;\n    }\n\n'
          f'    public static {name} fromCode(int code) {{\n'
          f'        for ({name} value : values()) {{\n'
          '            if (value.code == code)\n                return value;\n        }\n\n'
          '        throw new IllegalArgumentException("Unknown ' + name + ': " + code);\n    }\n}\n')

# Snapshot the numeric fields in declaration order. Address members in path
# stats are passed separately, so no native ABI layout leaks into Java.
stats = []
for c_name, name in [('quiche_stats', 'Stats'), ('quiche_transport_params', 'TransportParams'),
                     ('quiche_path_stats', 'PathStats'), ('quiche_h3_stats', 'H3Stats')]:
    body = re.search(r'typedef struct \{([^{}]*)\} ' + c_name + ';', HEADER, re.S)[1]
    fields = re.findall(r'^\s*(size_t|ssize_t|uint64_t|bool)\s+(\w+);', body, re.M)
    stats.append((c_name, name, fields))
    members = ''
    assigns = ''
    getters = ''
    for i, (typ, field) in enumerate(fields):
        java_type = 'boolean' if typ == 'bool' else 'PathState' if field == 'validation_state' else 'long'
        members += f'    public final {java_type} {camel(field)};\n\n'
        expr = f'values[{i}] != 0' if typ == 'bool' else f'PathState.fromCode((int) values[{i}])' if field == 'validation_state' else f'values[{i}]'
        assigns += f'        this.{camel(field)} = {expr};\n'
        getters += f'\n    public {java_type} {camel(field)}() {{\n        return {camel(field)};\n    }}\n'
    addresses = name == 'PathStats'
    if addresses:
        members += '    public final java.net.InetSocketAddress localAddress;\n\n    public final java.net.InetSocketAddress peerAddress;\n\n'
        assigns += '        this.localAddress = localAddress;\n        this.peerAddress = peerAddress;\n'
    write(name, '/** Immutable snapshot of {@code ' + c_name + '} (native durations retain their units). */\n'
          f'public final class {name} {{\n' + members +
          f'    {name}(long[] values' + (', java.net.InetSocketAddress localAddress,\n            java.net.InetSocketAddress peerAddress' if addresses else '') + ') {\n' +
          f'        if (values.length != {len(fields)})\n            throw new IllegalArgumentException("Invalid native snapshot");\n\n' + assigns + '    }\n' + getters + '}\n')

config_body = re.sub(r'//[^\n]*', '', HEADER[:HEADER.index('// Extracts version')])
config_setters = re.findall(r'(void|int) (quiche_config_\w+)\(quiche_config \*config,\s*(bool|uint64_t|size_t|enum quiche_cc_algorithm) (\w+)\);', config_body)
methods = []
cases = []
for i, (ret, fn, typ, arg) in enumerate(config_setters):
    method = camel(fn.removeprefix('quiche_config_'))
    java_type = 'boolean' if typ == 'bool' else 'CongestionControlAlgorithm' if typ.startswith('enum') else 'long'
    validation = '        java.util.Objects.requireNonNull(value, "value");\n' if java_type == 'CongestionControlAlgorithm' else ''
    if typ == 'size_t':
        validation = '        if (value < 0)\n            throw new IllegalArgumentException("value must be nonnegative");\n'
    if typ == 'uint64_t':
        # QUIC config values are counts, windows and durations, not arbitrary u64 IDs.
        validation = '        if (value < 0)\n            throw new IllegalArgumentException("value must be nonnegative");\n'
    expr = 'value ? 1 : 0' if typ == 'bool' else 'value.code()' if java_type == 'CongestionControlAlgorithm' else 'value'
    methods.append(f'    /** Maps {{@code {fn}}}. */\n    public Config {method}({java_type} value) {{\n' +
                   (validation + '\n' if validation else '') +
                   f'        synchronized (lock) {{\n            Native.configSet(pointer(), {i}, {expr});\n        }}\n\n'
                   '        return this;\n    }\n')
    call = f'{fn}(config, ({typ}) value)'
    cases.append(f'        case {i}: ' + (f'result = {call};' if ret == 'int' else f'{call};') + ' break;')
config = '''import java.nio.charset.StandardCharsets;
import java.util.Objects;

/** Native quiche configuration. Defaults are upstream defaults; close explicitly. */
public final class Config extends NativeResource {
    public Config(long version) {
        super(Native.configNew(Checks.u32(version)), 0);
    }

    public Config() {
        this(Quiche.PROTOCOL_VERSION);
    }

    private Config text(int option, String value) {
        synchronized (lock) {
            Native.configText(pointer(), option, Native.utf8(value));
        }

        return this;
    }

    public Config loadCertChainFromPemFile(String path) {
        return text(0, path);
    }

    public Config loadPrivKeyFromPemFile(String path) {
        return text(1, path);
    }

    public Config loadVerifyLocationsFromFile(String path) {
        return text(2, path);
    }

    public Config loadVerifyLocationsFromDirectory(String path) {
        return text(3, path);
    }

    public Config setCurvesList(String curves) {
        return text(4, curves);
    }

    public Config setCcAlgorithmName(String algorithm) {
        return text(5, algorithm);
    }

    /** ALPN values encoded as length-prefixed byte strings, as in the C API. */
    public Config setApplicationProtos(byte[] protocols) {
        Objects.requireNonNull(protocols, "protocols");
        if (protocols.length == 0)
            throw new IllegalArgumentException("Empty ALPN list");

        for (int i = 0; i < protocols.length;) {
            int length = protocols[i++] & 255;
            if (length == 0 || length > protocols.length - i)
                throw new IllegalArgumentException("Invalid ALPN list");

            i += length;
        }

        synchronized (lock) {
            Native.configBytes(pointer(), 0, protocols);
        }

        return this;
    }

    public Config setApplicationProtos(String... protocols) {
        java.io.ByteArrayOutputStream out = new java.io.ByteArrayOutputStream();
        for (String protocol : protocols) {
            byte[] value = Objects.requireNonNull(protocol, "protocol").getBytes(StandardCharsets.UTF_8);
            if (value.length == 0 || value.length > 255)
                throw new IllegalArgumentException("Invalid ALPN length");

            out.write(value.length);
            out.write(value, 0, value.length);
        }

        return setApplicationProtos(out.toByteArray());
    }

    public Config setStatelessResetToken(byte[] token) {
        if (Objects.requireNonNull(token, "token").length != 16)
            throw new IllegalArgumentException("Reset token must be 16 bytes");

        synchronized (lock) {
            Native.configBytes(pointer(), 1, token);
        }

        return this;
    }

    public Config setTicketKey(byte[] key) {
        Objects.requireNonNull(key, "key");
        if (key.length != 48)
            throw new IllegalArgumentException("Ticket key must be 48 bytes");

        synchronized (lock) {
            Native.configBytes(pointer(), 2, key);
        }

        return this;
    }

    public Config logKeys() {
        synchronized (lock) {
            Native.configFlag(pointer(), 0);
        }

        return this;
    }

    public Config enableEarlyData() {
        synchronized (lock) {
            Native.configFlag(pointer(), 1);
        }

        return this;
    }

    public Config enableDgram(boolean enabled, int receiveQueueLength, int sendQueueLength) {
        Checks.nonnegative(receiveQueueLength);
        Checks.nonnegative(sendQueueLength);

        synchronized (lock) {
            Native.configDgram(pointer(), enabled, receiveQueueLength, sendQueueLength);
        }

        return this;
    }

'''
write('Config', config + '\n'.join(methods) + '}\n')

c = LICENSE + '// Generated by scripts/generate_api.py.\n'
c += '''JNIEXPORT void JNICALL JN(configSet)(JNIEnv *env, jclass cls, jlong handle, jint option, jlong value) {
    quiche_config *config = PTR(quiche_config, handle);
    int result = 0;
    switch (option) {
''' + '\n'.join(cases) + '''
        default: invalid(env, "Unknown config option"); return;
    }
    check(env, result);
}
'''
for c_name, name, fields in stats:
    # Plain constructors consume copied data; no native pointer survives.
    func = 'h3Stats' if name == 'H3Stats' else camel(c_name.removeprefix('quiche_'))
    args = ', jint index' if name == 'PathStats' else ''
    native_type = 'quiche_h3_conn' if name == 'H3Stats' else 'quiche_conn'
    call = 'quiche_h3_conn_stats' if name == 'H3Stats' else 'quiche_conn_' + c_name.removeprefix('quiche_').replace('transport_params', 'peer_transport_params')
    if name == 'PathStats':
        line = f'    if (check(env, {call}(PTR({native_type}, handle), (size_t) index, &out)) < 0) return NULL;\n'
    elif name == 'TransportParams':
        line = f'    if (!{call}(PTR({native_type}, handle), &out)) return NULL;\n'
    else:
        line = f'    {call}(PTR({native_type}, handle), &out);\n'
    c += f'JNIEXPORT jobject JNICALL JN({func})(JNIEnv *env, jclass cls, jlong handle{args}) {{\n    {c_name} out;\n' + line
    c += '    jlong values[] = { ' + ', '.join(f'(jlong) out.{field}' for typ, field in fields) + ' };\n'
    c += f'    jlongArray data = longs(env, values, {len(fields)});\n'
    if name == 'PathStats':
        c += '    jobject local = java_address(env, (struct sockaddr *) &out.local_addr);\n    jobject peer = java_address(env, (struct sockaddr *) &out.peer_addr);\n'
        c += f'    jobject result = construct(env, "{name}", "([JLjava/net/InetSocketAddress;Ljava/net/InetSocketAddress;)V", data, local, peer);\n'
        c += '    (*env)->DeleteLocalRef(env, local); (*env)->DeleteLocalRef(env, peer);\n'
    else:
        c += f'    jobject result = construct(env, "{name}", "([J)V", data);\n'
    c += '    (*env)->DeleteLocalRef(env, data); return result;\n}\n'
c += 'JNIEXPORT jintArray JNICALL JN(enumValues)(JNIEnv *env, jclass cls) {\n    jint values[] = { ' + ', '.join(native_constants) + ' };\n'
c += f'    jintArray result = (*env)->NewIntArray(env, {len(native_constants)});\n    if (result) (*env)->SetIntArrayRegion(env, result, 0, {len(native_constants)}, values);\n    return result;\n}}\n'
(ROOT / 'native/src/main/c/generated.inc').write_text(c, encoding='ascii')

if __name__ == '__main__':
    print('Generated enums, Config, struct snapshots and JNI mappings.')
