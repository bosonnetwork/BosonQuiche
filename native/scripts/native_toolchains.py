def cmake_preamble(header):
    return (''.join('#' + (' ' + line[3:] if line.startswith(' * ') else '') + '\n'
                    for line in header.splitlines()[1:-1]) +
            '# Generated by native/scripts/build_native.py.\n\n')


def verify_windows_crt(sdk, expected):
    """Check the installed package build, not its Visual Studio component ID."""
    header = sdk / 'xwin/crt/include/crtversion.h'
    if not header.is_file():
        raise RuntimeError('Missing MSVC CRT version header: ' + str(header))
    text = header.read_text()
    parts = []
    for part in ('MAJOR', 'MINOR', 'BUILD'):
        value = re.search(r'^\s*#\s*define\s+_VC_CRT_' + part + r'_VERSION\s+(\d+)\b', text, re.M)
        if value is None:
            raise RuntimeError('Missing MSVC CRT ' + part.lower() + ' version: ' + str(header))
        parts.append(value[1])
    actual = '.'.join(parts)
    if actual != expected:
        raise RuntimeError('MSVC CRT package version mismatch: expected ' + expected + ', found ' + actual)
    return actual


def prepare_windows_sdk(sdk, pins, env, work):
    """Let cargo-xwin install its SDK, then verify the exact CRT package build."""
    env.update(XWIN_CACHE_DIR=str(sdk), XWIN_SDK_VERSION=pins['windows_sdk'],
               XWIN_CRT_VERSION=pins['windows_crt_component'])
    log_path = work / 'windows-sdk.log'
    print('Preparing Windows SDK and MSVC CRT component:', pins['windows_crt_component'], flush=True)
    with log_path.open('w') as log:
        result = subprocess.run(['cargo', 'xwin', 'cache', 'xwin'], env=env,
                                stdout=log, stderr=subprocess.STDOUT)
    if result.returncode:
        print('\n'.join(log_path.read_text().splitlines()[-45:]), file=sys.stderr)
        raise RuntimeError('Windows SDK setup failed; inspect ' + str(log_path))
    verify_windows_crt(sdk, pins['windows_crt'])


def ndk_path(pins):
    explicit = os.environ.get('ANDROID_NDK_HOME')
    return Path(explicit).resolve() if explicit else ROOT / '.build/toolchains' / pins['android']['directory']


def rust_version_supported(compiler, minimum):
    """Accept the installed compiler when it meets the upstream minimum."""
    version = re.match(r'^rustc (\d+)\.(\d+)\.(\d+)(?:[-+]\S+)?(?:\s|$)', compiler)
    return version is not None and tuple(map(int, version.groups())) >= tuple(map(int, minimum.split('.')))


def fetch_ndk(pins):
    """Install the checksum-pinned SDK into the project cache, never the user's SDK."""
    spec = pins['android']
    destination = ROOT / '.build/toolchains'
    installed = destination / spec['directory'] / 'source.properties'
    archive = ROOT / '.build/downloads' / spec['url'].rsplit('/', 1)[1]
    archive.parent.mkdir(parents=True, exist_ok=True)
    if not archive.exists():
        temporary = archive.with_suffix('.part')
        with urllib.request.urlopen(spec['url'], timeout=60) as response, temporary.open('wb') as stream:
            shutil.copyfileobj(response, stream)
        if digest(temporary) != spec['sha256']:
            raise RuntimeError('Downloaded NDK checksum mismatch; archive was not extracted')
        temporary.replace(archive)
    if digest(archive) != spec['sha256']:
        raise RuntimeError('Cached NDK checksum mismatch: ' + str(archive))
    if not installed.exists():
        with zipfile.ZipFile(archive) as package:
            for name in package.namelist():
                path = (destination / name).resolve()
                if not path.is_relative_to(destination.resolve()):
                    raise RuntimeError('Unsafe NDK archive path')
        destination.mkdir(parents=True, exist_ok=True)
        subprocess.run(['unzip', '-q', str(archive), '-d', str(destination)], check=True)
    if not re.search(r'Pkg.Revision\s*=\s*' + re.escape(spec['revision']) + r'\s*$', installed.read_text(), re.M):
        raise RuntimeError('Installed NDK revision mismatch')
    print('Verified project-local NDK:', installed.parent)


def preflight(pins):
    result = {'host': platform.platform(), 'tools': {}, 'docker': {}, 'android': {}}
    for name in ['python3', 'rustc', 'cargo', 'cmake', 'ninja', 'docker']:
        path = shutil.which(name)
        result['tools'][name] = {'path': path}
        if path and name in ('rustc', 'cargo', 'cmake', 'ninja'):
            result['tools'][name]['version'] = output(path, '--version').splitlines()[0]
    if shutil.which('docker'):
        try:
            result['docker'] = {'ready': True, 'server': json.loads(output('docker', 'version', '--format', '{{json .Server}}'))}
        except subprocess.CalledProcessError:
            result['docker'] = {'ready': False, 'action': 'Start OrbStack/Docker and ensure the Docker socket is accessible.'}
    ndk = ndk_path(pins)
    properties = ndk / 'source.properties'
    result['android'] = {'path': str(ndk), 'ready': properties.is_file(), 'expected_revision': pins['android']['revision']}
    if properties.is_file():
        result['android']['properties'] = properties.read_text().splitlines()
        result['android']['ready'] = bool(re.search(
            r'Pkg.Revision\s*=\s*' + re.escape(pins['android']['revision']) + r'\s*$',
            properties.read_text(), re.M))
    else:
        result['android']['action'] = 'Install the pinned NDK in this project cache, or set ANDROID_NDK_HOME.'
    result['rust_targets'] = output('rustup', 'target', 'list', '--installed').splitlines() if shutil.which('rustup') else []
    result['rust_minimum'] = pins['rust_minimum']
    result['rust_supported'] = rust_version_supported(
        result['tools'].get('rustc', {}).get('version', ''), pins['rust_minimum'])
    result['images'] = {}
    if result['docker'].get('ready'):
        images = [pins['windows_image']] + [pins['linux_image_prefix'] + arch for arch in ('amd64', 'arm64')]
        for image in images:
            try:
                result['images'][image] = output('docker', 'image', 'inspect', image, '--format', '{{.Id}}').strip()
            except subprocess.CalledProcessError:
                result['images'][image] = None
    print(json.dumps(result, indent=2))
    ready = (result['docker'].get('ready') and result['android']['ready']
             and len(result['images']) == 3 and all(result['images'].values())
             and result['rust_supported']
             and 'aarch64-linux-android' in result['rust_targets'])
    return 0 if ready else 1


def prepare_driver(source, work, lock, header):
    """Regenerate the lockfile driver crate; maintenance commands only."""
    driver = work / 'driver'
    (driver / 'src').mkdir(parents=True, exist_ok=True)
    manifest = ('[package]\nname = "boson-quiche-build"\nversion = "0.1.0"\nedition = "2021"\n'
                '[workspace]\n[lib]\ncrate-type = ["staticlib"]\n[dependencies]\n'
                'quiche = { path = ' + json.dumps(str(source / 'quiche')) +
                ', features = ' + json.dumps(FEATURES) + ' }\n[profile.release]\ndebug = false\n')
    config.write_if_changed(driver / 'Cargo.toml', manifest)
    config.write_if_changed(driver / 'src/lib.rs', header.read_text() +
        '// Generated by native/scripts/build_native.py.\npub use quiche::*;\n')
    config.write_if_changed(driver / 'Cargo.lock', lock.read_text())
    return driver


def build_windows_archive(target, pins, work, env, source, build):
    """Produce the MSVC static archive with cargo-xwin before CMake configures."""
    driver = prepare_driver(source, work, config.ROOT / 'native/Cargo.lock',
                            config.ROOT / 'native/copyright-header.txt')
    build_env = dict(env, CARGO_TARGET_DIR=str(build / 'rust'))
    command = ['cargo', 'xwin', 'rustc', '--release', '--locked', '--target',
               TARGETS[target].rust, '--manifest-path', str(driver / 'Cargo.toml')]
    print('Building the Windows archive with cargo-xwin', flush=True)
    subprocess.run(command, env=build_env, check=True)
    return build / 'rust' / TARGETS[target].rust / 'release' / 'boson_quiche_build.lib'


def prepare_windows_toolchain(target, pins, cache, work, env, source, build):
    """Provision the pinned MSVC toolchain through cargo-xwin.

    Cross-compiling PE code is a toolchain provisioning step, not a build flag, so
    it stays here; the compile itself is the CMake project's job.
    """
    sdk = cache / ('xwin-llvm20-sdk' + pins['windows_sdk'] + '-crt' + pins['windows_crt'])
    sdk.mkdir(parents=True, exist_ok=True)
    # cargo-xwin 0.23.1 does not tolerate simultaneous symlink creation.
    link = sdk / 'clang-cl'
    try:
        link.symlink_to(shutil.which('clang'))
    except FileExistsError:
        if not link.exists():
            raise RuntimeError('Stale compiler symlink in ' + str(sdk))
    env.update(LIBCLANG_PATH='/usr/lib/llvm-20/lib',
               RUSTFLAGS='-C target-feature=+crt-static',
               PATH=str(sdk) + os.pathsep + env['PATH'])
    prepare_windows_sdk(sdk, pins, env, work)
    triple = TARGETS[target].rust
    toolchain = sdk / 'cmake/clang-cl' / (triple + '-toolchain.cmake')
    # cargo-xwin generates its CMake integration during its first build, so the
    # pinned archive is always built here, before CMake can target MSVC.
    build_windows_archive(target, pins, work, env, source, build)
    if not toolchain.is_file():
        raise RuntimeError('cargo xwin did not provide ' + str(toolchain))
    return {'sdk': sdk, 'toolchain': toolchain,
            'report': {'cargo_xwin': output('cargo', 'xwin', '--version').strip(),
                       'compiler': output(str(sdk / 'clang-cl'), '--target=' + triple, '--version').strip(),
                       'windows_sdk': pins['windows_sdk'],
                       'windows_crt': pins['windows_crt'],
                       'windows_crt_component': pins['windows_crt_component'],
                       'crt_linkage': 'static'}}


def inspect_archive(archive, target, work, tools):
    expected = TARGETS[target].machine
    if target == 'macos-arm64':
        headers = output('lipo', '-info', str(archive))
        symbols = output(str(tools / 'llvm-nm'), '--defined-only', '--extern-only', str(archive))
        if 'architecture: arm64' not in headers:
            raise RuntimeError('Unexpected macOS archive architecture: ' + headers)
        machines = ['arm64']
    else:
        headers = output(str(tools / 'llvm-readobj'), '--file-headers', str(archive))
        symbols = output(str(tools / 'llvm-nm'), '--defined-only', '--extern-only', str(archive))
        machines = sorted(set(re.findall(r'^\s*Machine: (\S+)', headers, re.M)))
        if machines != [expected]:
            raise RuntimeError('Mixed or unexpected archive machines: ' + repr(machines))
    for symbol in SYMBOLS:
        if not re.search(r'\b_?' + symbol + r'\s*$', symbols, re.M):
            raise RuntimeError('Missing FFI symbol: ' + symbol)
    (work / 'archive-headers.txt').write_text(headers)
    (work / 'archive-symbols.txt').write_text(symbols)
    return machines


def link_windows_smoke(archive, target, work, source, sdk_cache, tools, env, license_header):
    """Prove that a Windows C consumer links, without claiming runtime execution."""
    smoke = work / 'link-proof'
    smoke.mkdir(exist_ok=True)
    (smoke / 'smoke.c').write_text(
        license_header + '// Generated by native/scripts/build_native.py.\n\n' +
        '#include <quiche.h>\n#include <string.h>\n'
        'int main(void) {\n'
        '    quiche_config *config = quiche_config_new(QUICHE_PROTOCOL_VERSION);\n'
        '    if (!config || strcmp(quiche_version(), "' + config.TAG + '"))\n        return 1;\n'
        '    quiche_config_free(config);\n    return 0;\n}\n')
    libraries = ['advapi32', 'legacy_stdio_definitions', 'kernel32', 'ntdll', 'userenv', 'ws2_32', 'dbghelp']
    paths = [archive] + sorted((work / 'link-support').glob('*.lib'))
    (smoke / 'CMakeLists.txt').write_text(
        cmake_preamble(license_header) +
        'cmake_minimum_required(VERSION 3.22)\nproject(quiche_link_proof C)\n'
        'add_executable(quiche_link_proof smoke.c)\n'
        'set_property(TARGET quiche_link_proof PROPERTY MSVC_RUNTIME_LIBRARY MultiThreaded)\n'
        f'target_include_directories(quiche_link_proof PRIVATE "{source}/quiche/include")\n'
        'target_link_libraries(quiche_link_proof PRIVATE ' +
        ' '.join('"' + str(p) + '"' for p in paths) + ' ' + ' '.join(libraries) + ')\n')
    toolchain = sdk_cache / 'cmake/clang-cl' / (TARGETS[target].rust + '-toolchain.cmake')
    link_env = dict(env, PATH=str(sdk_cache) + os.pathsep + env['PATH'])
    with (work / 'link-proof.log').open('w') as log:
        subprocess.run(['cmake', '-S', str(smoke), '-B', str(smoke / 'build'), '-G', 'Ninja',
                        '-DCMAKE_BUILD_TYPE=Release', '-DCMAKE_TOOLCHAIN_FILE=' + str(toolchain)],
                       env=link_env, stdout=log, stderr=subprocess.STDOUT, check=True)
        subprocess.run(['cmake', '--build', str(smoke / 'build')], env=link_env,
                       stdout=log, stderr=subprocess.STDOUT, check=True)
    binary = smoke / 'build/quiche_link_proof.exe'
    imports = output(str(tools / 'llvm-readobj'), '--file-headers', '--coff-imports', str(binary))
    (work / 'link-proof-imports.txt').write_text(imports)
    if TARGETS[target].machine not in imports:
        raise RuntimeError('Linked executable has the wrong machine type')
    return {'status': 'linked', 'executed': False, 'sha256': digest(binary),
            'dll_imports': sorted(set(re.findall(r'^\s*Name: ([^\s]+\.dll)', imports, re.M | re.I)))}


def collect_licenses(driver, source, work, cargo_home, triple, env, offline=True):
    """Collect notices from the resolved normal/build dependency graph."""
    command = ['cargo', 'tree', '--locked']
    if offline:
        command.append('--offline')
    command += ['--manifest-path', str(driver / 'Cargo.toml'), '--target', triple,
                '--edges', 'normal,build', '--prefix', 'none', '--format', '{p}']
    tree = output(*command, env=env)
    packages = sorted(set(re.findall(r'^([\w-]+) v([\d.]+[^\s]*)', tree, re.M)))
    destination = work / 'licenses'
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir()
    records = []
    for name, version in packages:
        if name == 'boson-quiche-build':
            continue
        directories = list(cargo_home.glob(f'registry/src/*/{name}-{version}'))
        if name in ('quiche', 'octets', 'qlog'):
            directories.append(source / name)
        notices = []
        for directory in directories:
            for path in sorted(directory.iterdir()):
                if path.is_file() and path.name.upper().startswith(('LICENSE', 'COPYING', 'NOTICE')):
                    target = destination / f'{name}-{version}' / path.name
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(path, target)
                    notices.append(target.relative_to(destination).as_posix())
            if name == 'boring-sys':
                target = destination / 'BoringSSL/LICENSE'
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(directory / 'deps/boringssl/LICENSE', target)
                notices.append('BoringSSL/LICENSE')
        if not notices:
            raise RuntimeError('No license notice found for resolved dependency ' + name + '-' + version)
        records.append({'package': name, 'version': version, 'notices': sorted(set(notices))})
    return records
